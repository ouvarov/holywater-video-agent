"""intake — make sure the dialogue line is known before anything is generated.

Contract: specs/intake.md."""

from __future__ import annotations

from hwva.context import Context, GateFailed, StageOutput
from hwva.schemas import IntakeData, LineSource
from hwva.text import detect_lang, extract_quoted_line, has_digits

ASK_LINE = "Що каже персонаж? Числа — словами. (Enter — хай придумає AI): "
ASK_DIGITS = "У репліці є цифри — напишіть числа словами (Enter — хай придумає AI): "
ASSUMPTION_LLM_LINE = "line will be generated by the LLM"
MAX_REWRITES = 3


def run(ctx: Context) -> StageOutput:
    params = ctx.manifest.params
    asked = False
    line: str | None = None
    source = LineSource.INPUT

    if params.get("line"):
        line = params["line"]
        # idempotent re-run: a line the user wrote/rewrote earlier stays `user`
        if params.get("line_source") == LineSource.USER.value:
            source = LineSource.USER
    else:
        line = extract_quoted_line(ctx.manifest.idea)
        if line is None and ctx.interactive:
            asked = True
            answer = ctx.ask(ASK_LINE).strip()
            if answer:
                line, source = answer, LineSource.USER

    if line is not None and has_digits(line):
        if not ctx.interactive:
            raise GateFailed(f"Write numbers in words in the line: {line!r}")
        line = _rewrite_digits(ctx)
        asked, source = True, LineSource.USER

    if line is None:
        # a --line with digits that the user declined to rewrite is dropped too
        params.pop("line", None)
        params.pop("line_source", None)
        if ASSUMPTION_LLM_LINE not in ctx.manifest.assumptions:
            ctx.manifest.assumptions.append(ASSUMPTION_LLM_LINE)
    else:
        params["line"] = line
        params["line_source"] = source.value
        if not params.get("lang"):
            params["lang"] = detect_lang(line)

    return StageOutput(data=IntakeData(asked=asked).model_dump())


def _rewrite_digits(ctx: Context) -> str | None:
    """Ask the user to rewrite the line with numbers in words; at most MAX_REWRITES questions.

    An empty answer means "let the LLM invent the line" -> None."""
    answer = ""
    for _ in range(MAX_REWRITES):
        answer = ctx.ask(ASK_DIGITS).strip()
        if not answer:
            return None
        if not has_digits(answer):
            return answer
    raise GateFailed(
        f"Write numbers in words in the line: {answer!r} "
        f"(still digits after {MAX_REWRITES} rewrites)"
    )
