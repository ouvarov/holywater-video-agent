# --- AC: idempotent re-run keeps line_source=user ----------------------------------------------


@pytest.mark.parametrize(
    ("idea", "params", "answers"),
    [
        (NO_QUOTES_IDEA, {}, ["Ну що, п'ять хвилин — і поїхали"]),
        (NO_QUOTES_IDEA, {"line": "Дай мені 2 гривні"}, ["Дай мені дві гривні"]),
    ],
    ids=["answered_question", "rewrote_digits"],
)
def test_rerun_keeps_user_line_source(
    make_ctx: MakeCtx, no_stdin: None, idea: str, params: dict[str, str], answers: list[str]
) -> None:
    ctx = make_ctx(idea=idea, params=params, interactive=True, answers=answers)
    intake.run(ctx)
    line = ctx.manifest.params["line"]
    assert ctx.manifest.params["line_source"] == LineSource.USER.value
    asked_first = list(_asked(ctx))

    intake.run(ctx)  # same manifest; no answers left, so any new question raises AssertionError
    assert _asked(ctx) == asked_first
    assert ctx.manifest.params["line"] == line
    assert ctx.manifest.params["line_source"] == LineSource.USER.value


